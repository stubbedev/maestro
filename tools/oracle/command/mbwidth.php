<?php
// Prints Go source for the code point ranges mb_strwidth() counts as
// width 2 (PHP 8.4 mbstring's East Asian Width table), for
// internal/command/mbwidth_table.go.
$ranges = [];
$start = null;
for ($cp = 0; $cp <= 0x10FFFF; $cp++) {
    $wide = false;
    if ($cp < 0xD800 || $cp > 0xDFFF) {
        $wide = mb_strwidth(mb_chr($cp, 'UTF-8'), 'UTF-8') === 2;
    }
    if ($wide && $start === null) {
        $start = $cp;
    } elseif (!$wide && $start !== null) {
        $ranges[] = [$start, $cp - 1];
        $start = null;
    }
}
if ($start !== null) {
    $ranges[] = [$start, 0x10FFFF];
}
echo "// Code generated by tools/oracle/command/mbwidth.php from PHP ".PHP_VERSION."'s mbstring; DO NOT EDIT.\n\n";
echo "package command\n\n";
echo "// mbWideRanges are the code points mb_strwidth counts as two columns.\n";
echo "var mbWideRanges = [][2]rune{\n";
foreach ($ranges as [$a, $b]) {
    printf("\t{0x%X, 0x%X},\n", $a, $b);
}
echo "}\n";
